async function main() {
  const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL })
  const allProducts = [
    ...COMMERCIAL_TIRES.map(buildTireProduct),
    ...COMMERCIAL_WHEELS.map(buildWheelProduct),
  ]

  let upserted = 0
  for (const p of allProducts) {
    await pool.query(
      `INSERT INTO products (id, slug, category, archived, data, updated_at)
       VALUES ($1, $2, $3, false, $4::jsonb, NOW())
       ON CONFLICT (id) DO UPDATE SET
         slug = EXCLUDED.slug,
         category = EXCLUDED.category,
         archived = false,
         data = EXCLUDED.data,
         updated_at = NOW()`,
      [p.id, p.slug, p.category, JSON.stringify(p)],
    )
    upserted += 1
  }

  const { rows } = await pool.query(
    `SELECT category, count(*)::int AS cnt FROM products
     WHERE archived = false
       AND (
         (category = 'tires' AND (data->'tire'->>'rim')::numeric != floor((data->'tire'->>'rim')::numeric))
         OR (category = 'wheels' AND (data->'wheel'->>'diameter')::numeric != floor((data->'wheel'->>'diameter')::numeric))
       )
     GROUP BY category`,
  )
  console.log(`Upserted ${upserted} commercial products. Commercial totals in DB:`, rows)
  await pool.end()
}

